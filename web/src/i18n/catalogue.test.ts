/// <reference types="node" />
// The English catalogue: every message parses, ids belong to their area, and the generated parameter types
// (generated/params.ts) match the messages. After changing a message's {arguments}:
//   KORA_UPDATE_I18N=1 npx vitest run src/i18n/catalogue
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { args, parse, type ArgKind } from './icu'

export const english = import.meta.glob<{ default: Record<string, string> }>('./en/**/*.ts', { eager: true })

export function allEnglish(): Array<[string, string, string]> {
  const out: Array<[string, string, string]> = []
  for (const [path, mod] of Object.entries(english)) {
    const area = path.replace('./en/', '').replace('.ts', '') // "servers/serversPage"
    for (const [id, text] of Object.entries(mod.default)) out.push([area, id, text])
  }
  return out
}

const TYPE: Record<ArgKind, string> = {
  any: 'string | number',
  number: 'number',
  date: 'Date | number',
  list: 'string[]',
  select: 'string',
  tag: 'Tag',
  node: 'ReactNode',
}

function generate(): string {
  const rows: string[] = []
  const rich: string[] = []
  for (const [, id, text] of allEnglish().sort((a, b) => a[1].localeCompare(b[1]))) {
    const a = args(parse(text))
    if (a.size === 0) continue
    rows.push(`  '${id}': { ${[...a].map(([n, k]) => `${n}: ${TYPE[k]}`).join('; ')} }`)
    if ([...a.values()].some((k) => k === 'tag' || k === 'node')) rich.push(`'${id}'`)
  }
  return `// Generated by \`KORA_UPDATE_I18N=1 npx vitest run src/i18n/catalogue\` from the English catalogue. Do not edit.
import type { ReactNode } from 'react'

type Tag = (children: ReactNode) => ReactNode

export interface MessageParams {
${rows.join('\n')}
}

/** Messages with <tags> or {pieces, node}: drawn with rich(), not t(). */
export type RichIds =${rich.length ? '\n  | ' + rich.join('\n  | ') : ' never'}
`
}

describe('the English catalogue', () => {
  const all = allEnglish()

  it('has messages', () => {
    expect(all.length).toBeGreaterThan(10)
  })

  it('every id starts with its area, and is unique', () => {
    const seen = new Set<string>()
    for (const [area, id] of all) {
      expect(id.startsWith(`${area.replace('/', '.')}.`), `${id} is in en/${area}.ts: ids are <folder>.<file>.<name>`).toBe(true)
      expect(seen.has(id), `duplicate id ${id}`).toBe(false)
      seen.add(id)
    }
  })

  it('every message parses', () => {
    for (const [, id, text] of all) {
      expect(() => parse(text), id).not.toThrow()
    }
  })

  it('the generated list of catalogue files is up to date', () => {
    const file = resolve(__dirname, 'generated/messages.ts')
    const names = Object.keys(english).sort()
    const want = `// Generated by \`KORA_UPDATE_I18N=1 npx vitest run src/i18n/catalogue\`: the type of every English catalogue file (nothing is bundled).\n${names.map((n, i) => `import type m${i} from '.${n.replace(/\.ts$/, '')}'`).join('\n')}\n\nexport type Messages = ${names.map((_, i) => `typeof m${i}`).join(' & ')}\n`
    if (process.env.KORA_UPDATE_I18N) writeFileSync(file, want)
    expect(readFileSync(file, 'utf8'), 'run: KORA_UPDATE_I18N=1 npx vitest run src/i18n/catalogue').toBe(want)
  })

  it('the generated parameter types are up to date', () => {
    const file = resolve(__dirname, 'generated/params.ts')
    const want = generate()
    if (process.env.KORA_UPDATE_I18N) writeFileSync(file, want)
    expect(readFileSync(file, 'utf8'), 'run: KORA_UPDATE_I18N=1 npx vitest run src/i18n/catalogue').toBe(want)
  })
})
